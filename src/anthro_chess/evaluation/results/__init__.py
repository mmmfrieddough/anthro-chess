"""The benchmark results store, its metric registry, and its reporting.

Benchmarks append results here; reports, comparisons, and later charts are
views over the store rather than ad-hoc operations over artifact files. That
inversion is what makes "compare this checkpoint against one from a year ago"
a query instead of a task.

Nothing in this package needs torch. Reading and reporting results has to work
wherever the repository is checked out, not only where a model can be loaded.
"""

